import { spawn, execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { readFile, mkdir, mkdtemp, writeFile } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
const repo = process.cwd();
const serial = process.argv[2];
if (!/^emulator-\d+$/.test(serial || '')) throw new Error('Supply a disposable emulator serial. This test refuses physical phones.');
const sdk = process.env.ANDROID_HOME || path.join(process.env.LOCALAPPDATA || '', 'Android/Sdk');
const adb = path.join(sdk, 'platform-tools', process.platform === 'win32' ? 'adb.exe' : 'adb');
const output = path.join(repo, 'artifacts/mobile-workspace-20261005');
await mkdir(output, { recursive: true });
const fixtureRoot = await mkdtemp(path.join(output, 'android-e2e-'));
const fixture = spawn(process.execPath, ['scripts/mobile-android-fixture.cjs', fixtureRoot], { cwd: repo, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
let fixtureLogs = ''; fixture.stdout.on('data', value => fixtureLogs += value); fixture.stderr.on('data', value => fixtureLogs += value);
const run = args => new Promise((resolve, reject) => {
  const child = spawn(adb, ['-s', serial, ...args], { windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] }); let logs = '';
  child.stdout.on('data', value => logs += value); child.stderr.on('data', value => logs += value); child.on('error', reject);
  const timer = setTimeout(() => { child.kill(); reject(new Error('Android command timed out')); }, 180000);
  child.on('exit', code => { clearTimeout(timer); code === 0 ? resolve(logs) : reject(new Error(logs)); });
});
try {
  for (let tries = 0; tries < 100 && !fixtureLogs.includes('fixture ready'); tries++) { if (fixture.exitCode !== null) throw new Error(fixtureLogs); await new Promise(r => setTimeout(r, 100)); }
  assert.match(fixtureLogs, /fixture ready/);
  assert.equal((await run(['shell', 'getprop', 'sys.boot_completed'])).trim(), '1', 'Emulator must finish booting first');
  await run(['install', '-r', path.join(repo, 'dist/android/profilepilot-phone.apk')]);
  await run(['install', '-r', path.join(repo, 'android-phone/app/build/outputs/apk/androidTest/debug/app-debug-androidTest.apk')]);
  const pairing = (await readFile(path.join(fixtureRoot, 'pairing.txt'), 'utf8')).trim();
  // The URI is generated by our isolated fixture; quote for Android's shell and
  // do not print its short-lived credential in diagnostics.
  assert.match(pairing, /^profilepilot:\/\/pair\?[A-Za-z0-9%&=+._:~-]+$/);
  const logs = await run(['shell', 'am', 'instrument', '-w', '-r', '-e', 'pairing', "'" + pairing + "'", '-e', 'class', 'io.github.profilepilot.phone.MobileWorkflowTest', 'io.github.profilepilot.phone.test/androidx.test.runner.AndroidJUnitRunner']);
  await writeFile(path.join(output, 'android-instrumentation.log'), logs);
  assert.match(logs, /OK \(1 test\)/, logs);
  const screenshots = path.join(output, 'mobile-verification'); await mkdir(screenshots, { recursive: true });
  for (const name of ['home', 'permissions', 'agent', 'task-paused', 'tasks', 'devices', 'settings', 'confirmation']) {
    const result = await promisify(execFile)(adb, ['-s', serial, 'exec-out', 'run-as', 'io.github.profilepilot.phone', 'cat', `files/mobile-verification/android-${name}.png`], { windowsHide: true, encoding: 'buffer', maxBuffer: 12 * 1024 * 1024 });
    assert.equal(result.stdout[0], 137, `Screenshot unavailable: ${name}`);
    await writeFile(path.join(screenshots, `android-${name}.png`), result.stdout);
  }
  const data = JSON.parse(await readFile(path.join(fixtureRoot, 'tasks/tasks.json'), 'utf8'));
  assert.ok(data.tasks.some(task => task.prompt.startsWith('Android native UI task')));
  assert.equal(data.tasks.filter(task => task.prompt === 'Lost response replay test').length, 1);
  console.log('Passed Android native UI, PC task creation, pause/resume, draft preservation, pinned TLS, encrypted credentials, retry, replies and revocation.');
} finally { fixture.kill(); fixture.stdout.destroy(); fixture.stderr.destroy(); }
