import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { launchProfilePilotE2e, repoRoot } from './e2e/lib/electron-driver.mjs';
const require = createRequire(import.meta.url);
const { TaskStore } = require('../dist/main/tasks/store');
const { usageCharge } = require('../dist/shared/task-cost');
let taskId;
const app = await launchProfilePilotE2e({ env: { CPM_START_VIEW: 'tasks' }, prepareFixture: async ({ dataDir }) => {
  const store = new TaskStore(path.join(dataDir, 'browser-tasks'));
  const task = store.create({ prompt: '整理今天的 AI 新闻，汇总页面来源', profileId: 'fixture' }, '测试浏览器');
  taskId = task.id; task.status = 'completed';
  task.modelRuns = [{ id: 'kimi-k3', endpoint: 'https://api.moonshot.cn', at: new Date().toISOString() }];
  Object.assign(task.usage, { inputTokens: 120000, outputTokens: 8000, jev: { inputTokens: 20000, calls: 5, elapsedMs: 5000 }, helper: { inputTokens: 2000, outputTokens: 500, calls: 2, elapsedMs: 1000 } });
  task.modelTokenUsage = [{ model: 'kimi-k3', inputTokens: 100000, outputTokens: 6000 }, { model: 'deepseek-flash', inputTokens: 20000, outputTokens: 2000 }];
  const at = Date.parse('2026-09-24T02:00:00Z');
  task.costRecords = [usageCharge('kimi', 'model', 'kimi-k3', 'https://api.moonshot.cn', at, at, { input_tokens: 100000, output_tokens: 6000 }), usageCharge('deepseek', 'model', 'deepseek-flash', 'https://api.deepseek.com', at, at, { input_tokens: 20000, output_tokens: 2000 })];
  store.save();
} });
try {
  const d = app.driver;
  await d.domInput('#prompt', '这份草稿需要保留');
  await d.domClick('[data-nav=usage]');
  assert.match((await d.query('.usage-metrics')).text, /150,500/);
  await d.domClick('[data-usage-source=model]');
  assert.match((await d.query('.usage-models')).text, /kimi-k3/);
  assert.match((await d.query('.usage-models')).text, /deepseek-flash/);
  assert.match((await d.query('.usage-models')).text, /106,000/);
  assert.match((await d.query('.usage-models')).text, /22,000/);
  assert.match((await d.query('.usage-costs')).text, /¥2\.600000/);
  assert.match((await d.query('.usage-costs')).text, /\$0\.008400/);
  await d.domClick('[data-usage-source=jev]');
  assert.match((await d.query('.usage-metrics')).text, /20,000/);
  assert.match((await d.query('.usage-metrics')).text, /—/);
  await d.domClick('[data-usage-source=helper]');
  assert.match((await d.query('.usage-metrics')).text, /2,500/);
  await d.domClick('[data-usage-source=all]');
  await d.evaluate('window.tasks.snapshot().then(({settings}) => window.tasks.saveSettings({...settings, notifications:false}))');
  assert.match((await d.query('.usage-metrics')).text, /150,500/);
  const dir = path.join(repoRoot, 'test-results', 'token-usage'); await mkdir(dir, { recursive: true });
  await d.screenshot(); await new Promise(r => setTimeout(r, 300));
  await writeFile(path.join(dir, 'usage.png'), Buffer.from((await d.screenshot()).pngBase64, 'base64'));
  await d.domClick('.usage-task-link');
  await d.waitFor('h1', s => s.text === '整理今天的 AI 新闻，汇总页面来源');
  await d.domClick('.sidebar [data-nav=tasks]');
  assert.equal((await d.query('#prompt')).value, '这份草稿需要保留');
  await d.evaluate(`window.tasks.deleteTask(${JSON.stringify(taskId)})`);
  await d.domClick('[data-nav=usage]');
  assert.match((await d.query('.usage-metrics')).text, /150,500/);
  assert.match((await d.query('.usage-records:not(.usage-models)')).text, /已删除的任务/);
  assert.match((await d.query('.usage-costs')).text, /¥2\.600000/);
  assert.match((await d.query('.usage-models')).text, /kimi-k3/);
  await d.evaluate('location.reload()');
  await d.waitFor('[data-nav=usage]'); await d.domClick('[data-nav=usage]');
  assert.match((await d.query('.usage-metrics')).text, /150,500/);
  console.log('PASS token usage: source filters, snapshots, task navigation, draft retention, deletion and reload');
} finally { await app.stop(); }
