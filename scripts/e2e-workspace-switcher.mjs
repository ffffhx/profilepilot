import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { launchProfilePilotE2e, repoRoot } from './e2e/lib/electron-driver.mjs';
const app=await launchProfilePilotE2e({name:'workspace switcher'});
try {
  const d=app.driver;
  if ((await d.query('button[data-action="dismiss-onboarding"]')).exists) await d.domClick('button[data-action="dismiss-onboarding"]');
  const dir=path.join(repoRoot,'test-results','workspace-switcher'); await mkdir(dir,{recursive:true});
  const shot=async name=>{await d.screenshot();await new Promise(r=>setTimeout(r,300));await writeFile(path.join(dir,name),Buffer.from((await d.screenshot()).pngBase64,'base64'));};
  const profile=await d.evaluate(`window.profileManager.createProfile('切换工作区测试').then(s=>s.profiles.find(p=>p.name==='切换工作区测试'))`);
  await d.domClick('[data-workspace-trigger]');
  await d.waitFor('#workspace-switch-menu:popover-open');
  assert.equal((await d.query('[data-workspace=browser]')).attributes['aria-checked'],'true');
  await shot('browser-switcher.png');
  await d.domClick('[data-workspace=agent]');
  await d.waitFor('#create-task');
  await d.waitFor('select[name=profileId]',s=>s.disabled===false);
  assert.equal((await d.query('.sidebar-footer a[href="./index.html"]')).exists,false);
  assert.match((await d.query('[data-workspace-trigger]')).text,/Agent/);
  await d.domInput('#prompt','切换工作区后保留这份草稿');
  await d.domInput('select[name=profileId]',profile.id);
  await d.domClick('#create-task details summary');
  await d.domInput('[name=templateName]','保留模板名称');
  const origin=await d.evaluate('performance.timeOrigin');
  await d.domClick('[data-workspace-trigger]');
  await shot('agent-switcher.png');
  await d.domClick('[data-workspace=agent]');
  assert.equal(await d.evaluate('performance.timeOrigin'),origin);
  assert.equal(await d.evaluate('document.querySelector("#prompt").value'),'切换工作区后保留这份草稿');
  await d.domClick('[data-workspace-trigger]');
  await d.evaluate('window.tasks.snapshot().then(({settings})=>window.tasks.saveSettings({...settings,notifications:false}))');
  assert.equal((await d.query('#workspace-switch-menu:popover-open')).exists,true);
  await d.dispatch('[data-workspace=agent]','keydown',{key:'ArrowDown'});
  assert.equal(await d.evaluate('document.activeElement.dataset.workspace'),'browser');
  await d.dispatch('[data-workspace=browser]','keydown',{key:'Escape'});
  assert.equal((await d.query('#workspace-switch-menu')).exists,false);
  await d.domClick('[data-workspace-trigger]');
  await d.domClick('[data-workspace=browser]');
  await d.waitFor('.browser-workspace-brand');
  await d.domClick('[data-workspace-trigger]');
  await d.domClick('[data-workspace=agent]');
  await d.waitFor('#prompt',s=>s.value==='切换工作区后保留这份草稿');
  await d.waitFor('select[name=profileId]',s=>s.value===profile.id);
  assert.equal(await d.evaluate('document.querySelector("[name=templateName]").value'),'保留模板名称');
  assert.equal(await d.evaluate('document.querySelector("#create-task details").open'),true);
  await d.domClick('[data-action=toggle-sidebar]');
  await d.domClick('[data-workspace-trigger]');
  assert.equal((await d.query('#workspace-switch-menu:popover-open')).exists,true);
  console.log('PASS workspace switcher: both directions, current selection without reload, keyboard, snapshots, collapsed sidebar and draft restoration');
} finally {await app.stop();}
