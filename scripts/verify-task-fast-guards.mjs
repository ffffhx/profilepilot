import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { startTaskFixture } from './browser-task-fixture.mjs';
const [profileId, portText] = process.argv.slice(2); const port = Number(portText);
assert.ok(profileId?.startsWith('isolated:') && Number.isInteger(port));
const require = createRequire(import.meta.url);
const { requestBrowserGateway } = require('../dist/main/browser-gateway-client');
const { WrapperBrowser } = require('../dist/main/tasks/browser');
const { TaskStore } = require('../dist/main/tasks/store');
const gatewayOptions = { homeDir: process.env.PROFILEPILOT_GATEWAY_HOME };
const state = await requestBrowserGateway({ action: 'status' }, gatewayOptions);
const profile = state.state.profiles.find(p => p.profileId === profileId && p.publicPort === port);
assert.ok(profile && (!profile.ownerSessionId || profile.sessionStatus === 'stopped'), 'Do not override an occupied profile.');
const fixture = await startTaskFixture();
const root = path.resolve('.cpm-data', `fast-guards-${Date.now()}`);
const store = new TaskStore(root), browser = new WrapperBrowser(path.join(root, 'artifacts'));
const task = store.create({ profileId, prompt: 'Verify DOM guards on local test site' }, profile.profileName); task.port = port;
const checks = [];
const evaluate = async expression => {
  const r = await browser.fast.raw(task, 'Runtime.evaluate', { expression, returnByValue: true });
  assert.equal(r.exceptionDetails, undefined); return r.result.value;
};
const observe = async () => task.observation = await browser.observeFast(task);
const action = (kind, candidate, value) => ({ kind, ref: candidate.ref, version: task.observation.version, effect: 'edit', summary: 'Local guard verification', value });
try {
  await browser.execute(task, { kind: 'open', value: `${fixture.url}/apply`, effect: 'read', summary: 'Open local guard fixture' });
  await observe();
  let field = task.observation.fast.candidates.find(c => c.kind === 'fill');
  await browser.execute(task, action('fill', field, '第一行\n第二行'));
  assert.equal(await evaluate('document.querySelector("input[name=name]").value'), '第一行第二行');
  checks.push('native input semantics');
  await observe(); field = task.observation.fast.candidates.find(c => c.kind === 'fill');
  await evaluate('document.querySelector("input[name=name]").value="changed by page"');
  await assert.rejects(browser.execute(task, action('fill', field, 'must not write')));
  assert.equal(await evaluate('document.querySelector("input[name=name]").value'), 'changed by page'); checks.push('changed values reject stale action');
  await observe(); let link = task.observation.fast.candidates.find(c => c.role === 'link');
  await evaluate('document.querySelector("a").href="/shop"');
  await assert.rejects(browser.execute(task, action('click', link)));
  assert.equal(await evaluate('location.pathname'), '/apply'); checks.push('changed link destinations reject stale click');
  await observe(); let checkbox = task.observation.fast.candidates.find(c => c.role === 'checkbox');
  await evaluate('document.querySelector("input[name=agree]").replaceWith(document.querySelector("input[name=agree]").cloneNode(true))');
  await assert.rejects(browser.execute(task, action('click', checkbox)));
  assert.equal(await evaluate('document.querySelector("input[name=agree]").checked'), false); checks.push('replaced nodes reject stale reference');
  await evaluate('var cover=document.createElement("div");cover.id="test-cover";cover.style="position:fixed;inset:0;z-index:2147483647;background:white";document.body.append(cover)');
  await observe(); checkbox = task.observation.fast.candidates.find(c => c.role === 'checkbox');
  await assert.rejects(browser.execute(task, action('click', checkbox)));
  assert.equal(await evaluate('document.querySelector("input[name=agree]").checked'), false); checks.push('occluded target cannot be clicked');
  await evaluate('document.querySelector("#test-cover").remove()');
  await observe(); checkbox = task.observation.fast.candidates.find(c => c.role === 'checkbox');
  await browser.execute(task, action('click', checkbox));
  assert.equal(await evaluate('document.querySelector("input[name=agree]").checked'), true); checks.push('single native click changes checkbox');
  await observe(); const before = task.observation;
  await browser.execute(task, { kind: 'open', value: `${fixture.url}/apply`, effect: 'read', summary: 'Reload local fixture' });
  task.observation = before;
  await assert.rejects(browser.execute(task, action('click', checkbox))); checks.push('new document invalidates old references');
  await evaluate('var p=document.createElement("input");p.type="password";p.value="not-for-model";document.body.append(p)');
  await observe();
  assert.equal(JSON.stringify(task.observation).includes('not-for-model'), false); checks.push('password values excluded');
  assert.equal(fixture.records.length, 0);
  const output = path.resolve('test-results/browser-tasks/fast-guards-result.json'); await mkdir(path.dirname(output), { recursive: true });
  await writeFile(output, JSON.stringify({ passed: true, at: new Date().toISOString(), profileId, port, checks }, null, 2));
  console.log('PASS', JSON.stringify({ checks, output }));
} finally {
  const latest = await requestBrowserGateway({ action: 'status' }, gatewayOptions);
  if (latest.state.profiles.some(p => p.ownerSessionId === task.sessionId)) await browser.control(task, 'complete');
  await fixture.close();
}
